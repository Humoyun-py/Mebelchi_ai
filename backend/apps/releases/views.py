from pathlib import PurePath

from django.conf import settings
from django.db.models import F
from django.http import FileResponse, Http404, HttpResponse, HttpResponseRedirect
from drf_spectacular.types import OpenApiTypes
from drf_spectacular.utils import extend_schema
from rest_framework import serializers
from rest_framework.permissions import AllowAny
from rest_framework.response import Response
from rest_framework.views import APIView

from . import services
from .models import AppRelease


class ReleaseSerializer(serializers.ModelSerializer):
    download_url = serializers.SerializerMethodField()

    class Meta:
        model = AppRelease
        fields = ["version_name", "version_code", "sha256", "size_bytes", "notes", "published_at", "download_url"]

    def get_download_url(self, obj) -> str:
        return f"/api/v1/app/android/{obj.version_code}/download/"


class AndroidReleasesView(APIView):
    """Public: the latest published Android build and the version history. Nothing is listed until an administrator publishes a build."""

    permission_classes = [AllowAny]
    authentication_classes = []

    @extend_schema(responses=OpenApiTypes.OBJECT)
    def get(self, request):
        rows = list(services.public_releases())
        data = ReleaseSerializer(rows, many=True).data
        return Response({"latest": data[0] if data else None, "releases": data})


class AndroidDownloadView(APIView):
    """Public: the APK itself (`latest` or a version code). The file is private media served here, never by nginx."""

    permission_classes = [AllowAny]
    authentication_classes = []

    @extend_schema(responses=OpenApiTypes.BINARY)
    def get(self, request, code=None):
        qs = services.public_releases()
        rel = qs.first() if code is None else qs.filter(version_code=code).first()
        if rel is None:
            raise Http404()
        name = f"mebelchi-ai-{rel.version_name}.apk"
        if rel.external_url:
            AppRelease.objects.filter(pk=rel.pk).update(download_count=F("download_count") + 1)
            resp = HttpResponseRedirect(rel.external_url)
            resp["X-Content-SHA256"] = rel.sha256
            resp["Cache-Control"] = "public, max-age=300"
            return resp
        prefix = getattr(settings, "RELEASES_X_ACCEL_PREFIX", "")
        if prefix:
            # nginx streams the file from its own read-only view of the media volume; the stored name is generated by the server
            stored = PurePath(rel.apk.name).name
            if not rel.apk.storage.exists(rel.apk.name):
                raise Http404()
            AppRelease.objects.filter(pk=rel.pk).update(download_count=F("download_count") + 1)
            resp = HttpResponse(content_type="application/vnd.android.package-archive")
            resp["X-Accel-Redirect"] = prefix.rstrip("/") + "/" + stored
            resp["Content-Disposition"] = f'attachment; filename="{name}"'
        else:
            try:
                handle = rel.apk.open("rb")
            except (FileNotFoundError, ValueError):
                raise Http404() from None
            AppRelease.objects.filter(pk=rel.pk).update(download_count=F("download_count") + 1)
            resp = FileResponse(handle, content_type="application/vnd.android.package-archive", as_attachment=True, filename=name)
        if not prefix:
            resp["Content-Length"] = str(rel.size_bytes)
        resp["X-Content-SHA256"] = rel.sha256
        resp["X-Content-Type-Options"] = "nosniff"
        resp["Cache-Control"] = "public, max-age=300"
        return resp
