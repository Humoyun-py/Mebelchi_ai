from django.conf import settings
from django.db import models


class TelegramLink(models.Model):
    """Binds one web account to one Telegram chat. The Telegram ID is never trusted on its own: it is stored only
    after a one-time code generated by the logged-in web user has been redeemed through the bot."""

    user = models.OneToOneField(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="telegram_link")
    telegram_id = models.BigIntegerField(unique=True)
    username = models.CharField(max_length=64, blank=True)
    linked_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.user_id} <-> {self.telegram_id}"


class LinkCode(models.Model):
    """One-time account-linking code. Only a keyed hash is stored, never the code itself."""

    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="telegram_link_codes")
    code_hash = models.CharField(max_length=64, db_index=True)
    expires_at = models.DateTimeField()
    used_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
